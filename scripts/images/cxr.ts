/**
 * Stylised, clearly labelled chest X-ray PLACEHOLDER (SVG). A realistic radiograph cannot be
 * generated procedurally; this only marks where a licensed image belongs.
 */

export interface CxrOptions {
  /** Second line of the banner. */
  caption: string;
  /** Dim the anatomy (used for the generic "no image" placeholder). */
  dimmed?: boolean;
}

export function renderCxrSvg(opts: CxrOptions): string {
  const W = 600;
  const H = 720;
  const op = opts.dimmed ? 0.45 : 1;
  const ribs: string[] = [];
  for (let i = 0; i < 9; i++) {
    const y = 175 + i * 38;
    const spread = 150 + i * 9;
    const drop = 40 + i * 3;
    // Posterior ribs: arcs from the spine outward and downward, both sides.
    ribs.push(`<path d="M290 ${y} C ${290 - spread * 0.6} ${y - 30}, ${300 - spread} ${y + 5}, ${300 - spread - 10} ${y + drop}"/>`);
    ribs.push(`<path d="M310 ${y} C ${310 + spread * 0.6} ${y - 30}, ${300 + spread} ${y + 5}, ${300 + spread + 10} ${y + drop}"/>`);
  }
  const vertebrae: string[] = [];
  for (let i = 0; i < 14; i++) vertebrae.push(`<rect x="284" y="${90 + i * 36}" width="32" height="30" rx="5"/>`);

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" font-family="Helvetica, Arial, sans-serif">
<title>Chest X-ray placeholder</title>
<desc>Schematic chest outline generated by scripts/generate-assets.ts. Not a radiograph and not diagnostic. Replace with a licensed image at the same path.</desc>
<defs>
<radialGradient id="bg" cx="50%" cy="45%" r="65%"><stop offset="0" stop-color="#2a2a2a"/><stop offset="1" stop-color="#050505"/></radialGradient>
<radialGradient id="lung" cx="50%" cy="40%" r="70%"><stop offset="0" stop-color="#0c0c0c"/><stop offset="1" stop-color="#262626"/></radialGradient>
<linearGradient id="soft" x1="0" x2="1"><stop offset="0" stop-color="#5a5a5a"/><stop offset="0.5" stop-color="#3a3a3a"/><stop offset="1" stop-color="#5a5a5a"/></linearGradient>
</defs>
<rect width="${W}" height="${H}" fill="url(#bg)"/>
<g opacity="${op}">
<path d="M70 690 C 60 480, 80 260, 160 160 C 200 115, 240 95, 300 92 C 360 95, 400 115, 440 160 C 520 260, 540 480, 530 690 Z" fill="url(#soft)"/>
<path d="M285 150 C 230 150, 170 190, 140 280 C 115 360, 110 450, 118 545 C 160 520, 230 515, 280 540 C 285 420, 288 280, 285 150 Z" fill="url(#lung)"/>
<path d="M315 150 C 370 150, 430 190, 460 280 C 485 360, 490 450, 482 545 C 440 520, 380 515, 345 540 C 330 420, 318 280, 315 150 Z" fill="url(#lung)"/>
<g fill="none" stroke="#bdbdbd" stroke-opacity="0.35" stroke-width="9" stroke-linecap="round">${ribs.join("")}</g>
<g fill="#d8d8d8" fill-opacity="0.35">${vertebrae.join("")}</g>
<path d="M300 300 C 270 300, 262 360, 255 420 C 248 470, 260 520, 300 530 C 360 540, 420 525, 430 480 C 438 440, 400 395, 360 370 C 335 350, 330 300, 300 300 Z" fill="#cfcfcf" fill-opacity="0.75"/>
<path d="M280 120 L 275 300 L 325 300 L 320 120 Z" fill="#bcbcbc" fill-opacity="0.5"/>
<path d="M300 140 C 240 120, 180 128, 120 150" fill="none" stroke="#e6e6e6" stroke-opacity="0.7" stroke-width="14" stroke-linecap="round"/>
<path d="M300 140 C 360 120, 420 128, 480 150" fill="none" stroke="#e6e6e6" stroke-opacity="0.7" stroke-width="14" stroke-linecap="round"/>
<path d="M110 560 C 150 500, 240 490, 290 545 L 310 545 C 360 500, 450 505, 490 560 L 530 690 L 70 690 Z" fill="#d6d6d6" fill-opacity="0.85"/>
</g>
<text x="40" y="70" font-size="40" font-weight="bold" fill="#f2f2f2">R</text>
<rect x="30" y="590" width="540" height="100" rx="10" fill="#000" fill-opacity="0.72" stroke="#ffcc00" stroke-width="3"/>
<text x="300" y="630" font-size="22" font-weight="bold" fill="#ffcc00" text-anchor="middle">PLACEHOLDER — replace with licensed image</text>
<text x="300" y="668" font-size="17" fill="#f2f2f2" text-anchor="middle">${opts.caption}</text>
</svg>
`;
}
