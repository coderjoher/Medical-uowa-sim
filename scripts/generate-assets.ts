/**
 * Generates the procedural PLACEHOLDER examination-finding assets in content/assets/:
 * auscultation sounds (WAV), 12-lead ECGs (SVG), chest X-ray placeholders (SVG) and manifest.json.
 *
 * Deterministic (seeded PRNG): re-running produces byte-identical files.
 * Usage (repo root): npx tsx scripts/generate-assets.ts [outDir]
 *
 * These are NOT recordings or real images. Replace them with licensed assets at the same paths
 * (see content/assets/README.md).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { encodeWav } from "./audio/wav.js";
import { SAMPLE_RATE, bowelNormal, heartSounds, lungCrackles, lungNormal, lungWheeze } from "./audio/sounds.js";
import { PRESETS, simulate } from "./ecg/model.js";
import { renderEcgSvg } from "./ecg/svg.js";
import { renderCxrSvg } from "./images/cxr.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(process.argv[2] ?? join(root, "content/assets"));

export interface ManifestEntry {
  path: string;
  kind: "sound" | "ecg" | "image";
  description: string;
  placeholder: true;
  /** Free-text clinical description of what the asset depicts (for authors; never shown as an answer). */
  depicts?: string;
}

const manifest: ManifestEntry[] = [];

function write(rel: string, data: string | Buffer, entry: Omit<ManifestEntry, "path" | "placeholder">) {
  const file = join(outDir, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, data);
  manifest.push({ path: rel, placeholder: true, ...entry });
  console.log(`  ${rel.padEnd(34)} ${(Buffer.byteLength(data) / 1024).toFixed(1).padStart(7)} KB`);
}

const WAV_INFO = (name: string) => ({
  INAM: name,
  ICMT: "Procedural placeholder generated by scripts/generate-assets.ts. Not a clinical recording.",
  ISFT: "medical-uowa-sim generate-assets",
});

console.log(`Writing placeholder assets to ${outDir}`);

// ── Sounds
const sounds: Array<[string, string, string, () => Float64Array]> = [
  ["sounds/heart-normal.wav", "Normal heart sounds", "S1 and S2 at 80 bpm, no added sounds or murmurs (apex). 12 beats, loops seamlessly.", () => heartSounds({ bpm: 80, beats: 12, seed: 11 })],
  ["sounds/heart-murmur-systolic.wav", "Heart sounds with ejection systolic murmur", "S1 and S2 at 80 bpm with a crescendo–decrescendo systolic murmur between S1 and S2. 12 beats, loops seamlessly.", () => heartSounds({ bpm: 80, beats: 12, murmur: "ejection-systolic", seed: 12 })],
  ["sounds/lung-normal.wav", "Normal vesicular breath sounds", "Vesicular breath sounds at 15 breaths/min; inspiration louder and longer than the short, soft expiratory phase. 2 breaths, loops seamlessly.", lungNormal],
  ["sounds/lung-wheeze.wav", "Expiratory wheeze", "Breath sounds with prolonged expiration and polyphonic musical expiratory wheeze (~400–750 Hz). 2 breaths, loops seamlessly.", lungWheeze],
  ["sounds/lung-crackles.wav", "Fine inspiratory crackles", "Vesicular breath sounds with fine, late-inspiratory crackles (short explosive clicks). 2 breaths, loops seamlessly.", lungCrackles],
  ["sounds/bowel-normal.wav", "Normal bowel sounds", "Intermittent low-pitched gurgles (~40/min) over a quiet background. 10 s, loops seamlessly.", () => bowelNormal(10)],
];
for (const [rel, name, depicts, gen] of sounds) {
  const samples = gen();
  write(rel, encodeWav(samples, SAMPLE_RATE, WAV_INFO(name)), {
    kind: "sound",
    description: `${name} (synthesised placeholder, 16-bit mono PCM WAV, ${SAMPLE_RATE} Hz, ${(samples.length / SAMPLE_RATE).toFixed(1)} s).`,
    depicts,
  });
}

// ── ECGs
for (const p of PRESETS) {
  const traces = simulate(p.params, 10, 250);
  write(`ecg/${p.id}.svg`, renderEcgSvg(traces, { heading: "12-lead ECG" }), {
    kind: "ecg",
    description: `${p.title} — simulated 12-lead ECG (3×4 + lead II rhythm strip, 25 mm/s, 10 mm/mV), placeholder SVG.`,
    depicts: p.interpretation,
  });
}

// ── Chest X-ray placeholders
write("images/cxr-normal.svg", renderCxrSvg({ caption: "Schematic PA chest (intended: normal CXR) — not diagnostic" }), {
  kind: "image",
  description: "Stylised PA chest outline standing in for a normal chest radiograph. Not a radiograph.",
  depicts: "Normal chest X-ray: normal heart size, clear lung fields, normal mediastinum.",
});
write("images/cxr-placeholder.svg", renderCxrSvg({ caption: "Image not available — schematic only, not diagnostic", dimmed: true }), {
  kind: "image",
  description: "Generic chest imaging placeholder for cases whose licensed image has not been supplied yet.",
});

const manifestJson = {
  $comment: "Generated by scripts/generate-assets.ts — do not edit by hand. Every entry is a procedural placeholder until replaced by a licensed asset.",
  generator: "scripts/generate-assets.ts",
  licence: "Generated procedurally in this repository; contains no third-party recordings, images or data.",
  assets: manifest,
};
writeFileSync(join(outDir, "manifest.json"), JSON.stringify(manifestJson, null, 2) + "\n");
console.log(`  manifest.json (${manifest.length} assets)`);
